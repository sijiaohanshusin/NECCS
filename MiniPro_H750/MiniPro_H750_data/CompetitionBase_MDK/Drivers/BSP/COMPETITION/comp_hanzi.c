#define COMP_HANZI_GLYPH_COUNT \
    ((uint16_t)(sizeof(s_glyphs) / sizeof(s_glyphs[0])))

static const comp_hanzi_glyph_t *comp_hanzi_find(uint16_t codepoint)
{
    uint16_t index;

    for (index = 0U; index < COMP_HANZI_GLYPH_COUNT; index++)
    {
        if (s_glyphs[index].codepoint == codepoint)
        {
            return &s_glyphs[index];
        }
    }

    return NULL;
}

static uint32_t comp_hanzi_decode_utf8(const uint8_t **cursor)
{
    const uint8_t *text = *cursor;
    uint32_t codepoint;

    if (text[0] < 0x80U)
    {
        *cursor = text + 1;
        return text[0];
    }

    if (((text[0] & 0xE0U) == 0xC0U) &&
        ((text[1] & 0xC0U) == 0x80U))
    {
        codepoint = ((uint32_t)(text[0] & 0x1FU) << 6U) |
                    (uint32_t)(text[1] & 0x3FU);
        *cursor = text + 2;
        return codepoint;
    }

    if (((text[0] & 0xF0U) == 0xE0U) &&
        ((text[1] & 0xC0U) == 0x80U) &&
        ((text[2] & 0xC0U) == 0x80U))
    {
        codepoint = ((uint32_t)(text[0] & 0x0FU) << 12U) |
                    ((uint32_t)(text[1] & 0x3FU) << 6U) |
                    (uint32_t)(text[2] & 0x3FU);
        *cursor = text + 3;
        return codepoint;
    }

    *cursor = text + 1;
    return (uint32_t)'?';
}

static void comp_hanzi_draw_missing(uint16_t x,
                                    uint16_t y,
                                    uint16_t foreground,
                                    uint16_t background)
{
    uint8_t row;
    uint8_t column;

    for (row = 0U; row < 16U; row++)
    {
        for (column = 0U; column < 16U; column++)
        {
            uint8_t border = (uint8_t)((row == 0U) || (row == 15U) ||
                                       (column == 0U) || (column == 15U));
            lcd_draw_point((uint16_t)(x + column),
                           (uint16_t)(y + row),
                           border ? foreground : background);
        }
    }
}

static void comp_hanzi_draw_glyph(uint16_t x,
                                  uint16_t y,
                                  const comp_hanzi_glyph_t *glyph,
                                  uint16_t foreground,
                                  uint16_t background)
{
    uint8_t row;
    uint8_t column;

    for (row = 0U; row < 16U; row++)
    {
        uint16_t bits = glyph->rows[row];

        for (column = 0U; column < 16U; column++)
        {
            uint16_t color = ((bits & ((uint16_t)0x8000U >> column)) != 0U) ?
                             foreground : background;
            lcd_draw_point((uint16_t)(x + column),
                           (uint16_t)(y + row),
                           color);
        }
    }
}

uint8_t comp_hanzi_has_glyph(uint16_t codepoint)
{
    return (comp_hanzi_find(codepoint) != NULL) ? 1U : 0U;
}

void comp_hanzi_show_utf8(uint16_t x,
                          uint16_t y,
                          const char *text,
                          uint16_t foreground,
                          uint16_t background)
{
    const uint8_t *cursor = (const uint8_t *)text;
    uint16_t start_x = x;
    uint32_t old_background = g_back_color;

    if (text == NULL)
    {
        return;
    }

    g_back_color = background;

    while (*cursor != 0U)
    {
        uint32_t codepoint = comp_hanzi_decode_utf8(&cursor);

        if (codepoint == (uint32_t)'\n')
        {
            x = start_x;
            y = (uint16_t)(y + 16U);
            continue;
        }

        if ((codepoint >= 0x20U) && (codepoint <= 0x7EU))
        {
            lcd_show_char(x, y, (char)codepoint, 16U, 0U, foreground);
            x = (uint16_t)(x + 8U);
        }
        else
        {
            const comp_hanzi_glyph_t *glyph =
                comp_hanzi_find((uint16_t)codepoint);

            if (glyph != NULL)
            {
                comp_hanzi_draw_glyph(x, y, glyph, foreground, background);
            }
            else
            {
                comp_hanzi_draw_missing(x, y, foreground, background);
            }
            x = (uint16_t)(x + 16U);
        }

        if (x >= lcddev.width)
        {
            x = start_x;
            y = (uint16_t)(y + 16U);
        }
        if (y >= lcddev.height)
        {
            break;
        }
    }

    g_back_color = old_background;
}
